"""Writes shared/exlib.txt into the Android library (LibraryMore.kt) and the web page (const LIBMORE)."""
import pathlib, re
ROOT = pathlib.Path(__file__).resolve().parent.parent
rows = (ROOT / "shared/exlib.txt").read_text().strip().split("\n")
# A JVM string constant is capped at 64 KB, so the text is split into chunks.
chunks, cur = [], []
for r in rows:
    if sum(len(x.encode()) + 1 for x in cur) + len(r.encode()) > 50_000: chunks.append(cur); cur = []
    cur.append(r)
chunks.append(cur)
def kq(s): return s.replace("$", "${'$'}")
kt = ['package app.liftlog.model', '',
      '// Generated by tools/exlib_sync.py from shared/exlib.txt: exercises from free-exercise-db',
      '// (public domain, github.com/yuhonas/free-exercise-db), renamed in Hevy\'s style. name|muscle|equipment|type|cue', '']
for i, c in enumerate(chunks): kt.append(f'private const val MORE_{i} = """' + kq("\n".join(c)) + '"""')
kt.append('')
kt.append('internal val MORE_TXT: String get() = listOf(' + ", ".join(f"MORE_{i}" for i in range(len(chunks))) + ').joinToString("\\n")')
(ROOT / "composeApp/src/commonMain/kotlin/app/liftlog/model/LibraryMore.kt").write_text("\n".join(kt) + "\n")
web = (ROOT / "web/index.html").read_text()
js = "const LIBMORE=" + repr("\n".join(rows)).replace("</", "<\\/") + ";"
if "const LIBMORE=" in web: web = re.sub(r"const LIBMORE=.*?;\n", lambda m: js + "\n", web, count=1, flags=re.S)
else: web = web.replace("const CUETXT=", js + "\nconst CUETXT=", 1)
(ROOT / "web/index.html").write_text(web)
print(len(rows), "exercises in", len(chunks), "chunks")
