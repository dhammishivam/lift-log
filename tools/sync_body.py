"""Generates the body map shapes for the app (BodyPaths.kt) and the web (const BODY=...) from shared/body.json.
shared/body.json comes from tools/body_gen.py (left-half shapes, mirrored). Run after changing either."""
import json, re, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
b = json.loads((root / "shared/body.json").read_text())
def kl(xs): return "listOf(" + ", ".join(f'"{x}"' for x in xs) + ")"
def km(d): return "mapOf(\n" + ",\n".join(f'        "{k}" to {kl(v)}' for k, v in d.items()) + ",\n    )"
kt = f'''// Generated by tools/sync_body.py from shared/body.json. Do not edit by hand.
package app.liftlog.ui

/** SVG path data for the body map, in a 200 × 420 box: the silhouette and each muscle, front and back. */
internal object BodyPaths {{
    val sil = {kl(b["sil"])}
    val front: Map<String, List<String>> = {km(b["front"])}
    val back: Map<String, List<String>> = {km(b["back"])}
}}
'''
(root / "composeApp/src/commonMain/kotlin/app/liftlog/ui/BodyPaths.kt").write_text(kt)
web = root / "web/index.html"; s = web.read_text()
line = "const BODY=" + json.dumps(b, separators=(",", ":")) + ";"
s = re.sub(r"const BODY=\{.*?\};", lambda m: line, s, count=1, flags=re.S) if "const BODY={" in s else s.replace("// Anatomical body map:", line + "\n// Anatomical body map:", 1)
web.write_text(s)
print("body shapes:", sum(len(v) for v in b["front"].values()), "front,", sum(len(v) for v in b["back"].values()), "back")
