"""Generates the body map data for the app (BodyPaths.kt) and the web (const BODY=...) from shared/body.json
(built by tools/body_import.py). Run after changing it."""
import json, re, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
b = json.loads((root / "shared/body.json").read_text())
def kl(xs): return "listOf(\n" + ",\n".join(f'            "{x}"' for x in xs) + ",\n        )"
def km(d): return "mapOf(\n" + ",\n".join(f'        "{k}" to {kl(v)}' for k, v in d.items()) + ",\n    )"
def view(v): return f'''BodyView(
        vb = floatArrayOf({", ".join(f"{x}f" for x in b[v]["vb"])}),
        base = {kl(b[v]["base"])},
        regions = {km(b[v]["regions"])},
    )'''
kt = f'''// Generated by tools/sync_body.py from shared/body.json. Do not edit by hand.
// {b["credit"]}
package app.liftlog.ui

/** One side of the body: its SVG viewBox (x, y, w, h), the non-muscle parts, and the paths of each region. */
internal class BodyView(val vb: FloatArray, val base: List<String>, val regions: Map<String, List<String>>)

internal object BodyPaths {{
    val front = {view("front")}
    val back = {view("back")}
}}
'''
(root / "composeApp/src/commonMain/kotlin/app/liftlog/ui/BodyPaths.kt").write_text(kt)
web = root / "web/index.html"; s = web.read_text()
line = "const BODY=" + json.dumps({k: b[k] for k in ("front", "back")}, separators=(",", ":")) + ";"
s = re.sub(r"const BODY=\{.*?\};\n", lambda m: line + "\n", s, count=1, flags=re.S)
web.write_text(s)
print("app + web body data written")
